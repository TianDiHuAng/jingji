"""续作GV：更新验证页"跨语言对照"的说明文字，使其准确。"""
p = 'tools/gen_site.py'
s = open(p, encoding='utf-8').read()

old = ('vb.append(\'<p class="src-list">以下数值中英文维基百科一致，但两者<b>同属维基体系</b>，'
       '不构成严格意义的独立机构互证，仅作跨语言对照记录。</p>\')')

