R['ricardian-equivalence'] = (
"""李嘉图等价(ricardian equivalence) 是一个命题：
**政府以债务融资减税，与以税收融资支出，对总需求的效果相同**——
因为家庭会预期未来的增税，
从而**把减税所得储蓄起来**而不是消费。
**逻辑链条**：当期减税 → 政府债务增加 → 
家庭预期未来税负上升 → 增加储蓄以应对 → 
消费不变 → 总需求不变。
**它对财政政策有效性的挑战是根本性的**：
若该命题成立，**财政刺激将完全失效**。
**但现实中它通常只是近似成立，原因有五**：
①**流动性约束**——穷人无法借到钱，因此拿到减税就会花掉；
②**代际利他有限**——人们未必关心子孙的税负；
③**不完全预期**——家庭未必意识到"今天的债是明天的税"；
④**税收的扭曲性**——未来增税带来的效率损失改变了等价条件；
⑤**债务期限与利率**——若利率低于增长率，滚动债务不必靠增税。
**因此经验共识大致是**：
**短期内等价不成立（财政有效），长期内趋近成立**。
**与危机的关系**：
危机中的财政扩张往往**确实有效**——
因为流动性约束普遍收紧、信心受挫、
且大量家庭与企业同时去杠杆（见 balance-sheet-recession）；
但在**接近充分就业**时，等价逻辑会重新占上风——
此时扩张更可能推高利率与通胀，而非产出。""")

