R['macroprudential'] = (
"""宏观审慎监管(macroprudential regulation) 指
**以整个金融体系为对象、旨在降低系统性风险**的监管框架，
与**微观审慎**（关注单个机构稳健）相对。
**两者的区别不在于工具，而在于视角与目标**：
同一项资本要求，若为"确保这家银行不倒"而设，是微观审慎；
若为"防止所有银行在同一时点同时收缩"而设，是宏观审慎。
**这一区分的关键依据是"合成谬误"**：
**所有机构分别采取审慎行动，可能产生系统性的不审慎结果**——
当每家银行都在压力下抛售资产、收紧信贷，
系统整体的收缩幅度远超任何单一机构的意图。
**主要工具**：
**逆周期资本缓冲**（繁荣期加码、危机期释放，
见 countercyclical-capital-buffer）；
**系统重要性机构的附加要求**（见 sifi）；
**贷款价值比与债务收入比上限**（抑制房地产杠杆）；
以及**压力测试**（见 stress-test）。
**与危机的关系**：
2008 年前的监管以微观审慎为主，
且普遍假设"机构会自我管理风险、市场纪律足够"；
危机暴露了这一假设的代价——
**监管者需要工具来约束"共同行为"而非仅"个别机构"**。
**它自身的困难**：
①**识别时点极难**——在繁荣期收紧会不受欢迎且缺乏"证据"；
②**跨境协调**——风险跨越法域，而监管权限不跨；
③**可能与货币政策冲突**——紧缩的宏观审慎会替代加息的部分功能，
两者的分工至今仍有争论。""")

