R['sticky-prices'] = (
"""名义刚性(sticky prices / nominal rigidity) 指**价格与工资
不能迅速调整以出清市场**的现象。
**为什么它如此重要**：
若价格与工资完全灵活，则需求下降会立刻转化为价格下降，
**产出与就业不受影响**（这是古典经济学的结论）；
而**正因为存在刚性，需求的变动才会产生实际的产出与失业效应**
——这正是凯恩斯主义的核心，也是政策有效性的前提。
**几种解释来源**：
**菜单成本**（见 menu-cost）——调价本身有成本；
**交错定价**——合约分批到期，价格调整滞后；
**效率工资**——企业主动支付高于市场的工资以提高 productivity；
**协调失败**——单个企业降价未必带来销量，等大家降又来不及。
**与危机的关系**：
①**通胀的惯性**——刚性使通胀一旦上升就难以迅速回落，
央行必须以更大的产出代价压低通胀（"牺牲率"）；
②**实际工资的调整滞后**——
衰退中名义工资下降困难，
企业只能通过**裁员**而非降薪来调整，
这使失业上升更快；
③**危机中刚性会下降**——极端不确定下企业更频繁重定价，
通胀对冲击的敏感度上升；
④**数字化正在削弱刚性**（自动调价、动态定价），
这是"通胀动态是否已改变"的争论焦点之一。
**一个必须注意的对称**：刚性既是**问题的来源**（失业），
也是**政策的空间**（若价格灵活，货币政策将完全无效）。""")

