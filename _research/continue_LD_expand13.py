R['convexity'] = (
"""凸性(convexity) 衡量**债券价格对利率变化的敏感度本身如何变化**，
即**久期的变化率**——
用数学语言说，它是价格—利率曲线的**二阶导数**。
**为什么必须与久期配对使用**：
**久期是一阶（线性）近似**——
它告诉你利率变动 1% 时价格大约变动多少，
但**利率变动越大，线性近似的误差越大**；
**凸性修正了这种弯曲**：
利率下降时价格的实际涨幅**大于**久期预测，
利率上升时实际跌幅**小于**久期预测。
**因此"正凸性"对持有人有利**——
它意味着"涨得多、跌得少"。
**与危机的关系**：
①**凸性对冲与"凸性交易"**是固定收益市场的常见策略，
而这类策略在波动率骤升时会失效甚至反向；
②**抵押贷款支持证券（见 mortgage-backed-security）的负凸性**
是个关键问题——当利率下降时，
借款人提前还款使投资者收回本金、
不得不以更低利率再投资（**提前还款风险**）；
③**保险与养老金的负债凸性**在利率变动时
会与资产端产生不匹配，放大偿付压力
（2022 年英国 LDI 危机中，负债端对利率的敏感度是关键）；
④**风险管理上**，只报告久期而不报告凸性，
在利率大幅波动时会**系统性低估损失**。""")

