R['ponzi-scheme'] = (
"""庞氏骗局(Ponzi scheme) 指**用新投资者的资金支付旧投资者回报**的欺诈结构，
其"收益"并非来自真实的经营或投资，而是来自资金的不断流入。
**它必然崩溃的原因（数学上的必然）**：
要维持支付，**新资金必须以递增速度流入**；
一旦流入放缓或停止，支付立即中断——
**因此它的存续时间只取决于"增长速度"，而非"是否盈利"**（它从不盈利）。
**识别特征**：
①**回报异常稳定且高**——真实投资不会如此平滑；
②**策略不透明**——拒绝说明如何获利；
③**提款受限**——鼓励续投、限制赎回；
④**拉人头奖励**——依赖社交网络扩张；
⑤**审计缺失或由关联方出具**。
**与危机的关联有两层**：
①**麦道夫的案例（2008 年曝光）** 说明——
**危机是揭穿庞氏骗局的催化剂**：
当赎回请求激增时，无法支付真相立即暴露；
②**更重要的概念联系**：
**明斯基的"庞氏融资"**（见 minsky-theory、minsky-moment）
**不是欺诈**，而是一种**融资结构**——
现金流连利息都不够，只能靠资产升值再融资维持。
**两者形式相似（都依赖持续流入），但性质不同**：
一个是犯罪，一个是脆弱性。
**这一区分很重要：不该把所有高杠杆结构都称为"庞氏"。**""")

R['bimetallism'] = (
"""复本位制(bimetallism) 指**同时以黄金与白银作为本位货币**、
并规定二者固定兑换比例的货币制度。
**它在 19 世纪是主流安排**，也是"金银之争"的制度背景。
**它的内在问题——格雷欣法则的经典场景**（见 greshams-law）：
①若法定比价与市场比价不一致，
**被高估的金属会充斥市场，被低估的会被熔化或窖藏**——
即"劣币驱逐良币"；
②**因此复本位制的稳定依赖于两种金属的市场比价恰好等于法定比价**，
而这一条件极难长期维持；
③**结果常是事实上的单本位**（实际只流通一种金属）。
**国际层面的尝试**：
**拉丁货币同盟**（1865 年，法国、意大利、瑞士、比利时）
试图通过协调维持复本位，
但随着各国相继转向金本位（1870 年代后）而瓦解。
**与危机的关系**：
①**19 世纪后期的"金银之争"是通缩性政治冲突**——
银价下跌使采用银本位的国家（如中国）货币贬值，
而金本位国家经历温和通缩（见 deflation），
**债务人的实际负担上升**，催生了美国的"自由银币"运动；
②**本位选择不是技术问题**——
它决定了**谁承担调整代价**（债务人 vs 债权人、
出口部门 vs 进口部门），因此总是政治性的；
③**1930 年代各国放弃金本位**（见 gold-standard 相关条目）
正是为了摆脱这一硬约束，与复本位的瓦解在逻辑上一致。""")

R['financial-fragility'] = (
"""金融脆弱性(financial fragility) 指**金融体系内在的、在冲击下容易失稳的性质**，
它是明斯基"金融不稳定假说"的核心（见 minsky-theory）。
**关键论点是"稳定孕育不稳定"**：
长期平稳会使**风险偏好上升、杠杆累积、
融资结构从对冲型（能偿付本息）向投机型与庞氏型漂移**——
于是体系**看起来最稳健的时候，恰恰最脆弱**。
**这一性质的几个来源**：
①**期限与流动性转换**——银行的功能本身即脆弱性
（见 fractional-reserve）；
②**杠杆**——小幅资产价格变动即可击穿净值（见 leverage）；
③**关联与共同暴露**——机构间敞口与相似持仓使冲击扩散
（见 systemic-risk、contagion）；
④**信息不对称**——危机中无法评估对手方，市场因此冻结
（见 information-asymmetry）；
⑤**顺周期机制**——抵押品估值、保证金、评级与资本要求
在压力下同时收紧（见 procyclicality）。
**一个必须说清的分辨**：
**脆弱性不等于"即将出事"**——
它是**结构性的条件**，而不是时点预测；
把它当作"危机将至"的信号是对该概念的误用。
**政策含义**：
既然脆弱性是内生的，
**监管不能假设"市场会自我纠正"**，
而必须**在繁荣期主动加码**（逆周期资本缓冲、
见 macroprudential）——
**这与"危机是外部冲击造成的"这一直觉正好相反**。""")

