R['national-income'] = (
"""国民收入与产出度量(national income accounting) 是
**系统记录一国经济活动的核算体系**，
其核心是 **GDP**（国内生产总值，见相关的 gdp 条目）
与 **GNI**（国民总收入）。
**两者的关键区别**：
**GDP** 按**地域**统计——在一国境内生产的全部最终产品与服务；
**GNI** 按**国民**统计——本国居民获得的全部收入
（含来自国外的要素收入，减去付给国外的）。
**因此**若一国有大量外资企业利润汇出，**GDP 会大于 GNI**。
**三个必须知道的核算原则**：
①**只计最终产品**（中间投入不重复计算）；
②**只计当期生产**（二手车交易、股票买卖不计入）；
③**按市场价格**（含间接税）。
**主要局限（这是危机分析中的常见陷阱）**：
①**不反映分配**——总量增长可以与多数人收入停滞并存；
②**不反映环境与家务等非市场活动**；
③**不反映金融脆弱性**——杠杆与资产泡沫**不在 GDP 中**，
这正是危机前"宏观数据看起来很好"的原因；
④**跨国比较需用购买力平价或统一货币**，且口径差异会影响结论。
**本库的处理**：引用任何 GDP 数据时**注明口径与来源**，
遇到不同来源不一致时并列呈现
（见 verification 页的「统计口径对照」）。""")

R['stress-test'] = (
"""压力测试(stress test) 指**在设定的极端但可能的情景下，
评估金融机构或体系的损失与资本充足程度**的方法。
**它与常规风险模型的区别**：
**常规模型**（如在险价值）基于历史波动与统计分布，
**对罕见事件几乎不敏感**；
**压力测试**则**人为设定情景**（如"房价下跌 30%、失业率升至 12%"），
直接测算冲击。
**它的两项核心产出**：
①**损失与资本缺口**（需要多少资本才能吸收冲击）；
②**对监管行动的触发**（是否需要限制分红或补充资本）。
**它的价值与局限必须并列**：
**价值**——能把"尾部风险"显性化，
并在危机中**恢复市场信心**（公开结果可减少信息不对称，
见 information-asymmetry）；
**局限**——
①**情景设计的主观性**——"合理的最坏情形"取决于设计者的想象，
而**下一次危机的形态往往不在上一轮的情景里**；
②**模型与数据的内部依赖**——结果可能过于乐观；
③**顺周期效应**——压力测试趋严会迫使银行同时收缩信贷
（见 procyclicality）；
④**"通过测试"可能被误读为"安全"**。
**与危机的关系**：
2009 年美国对大型银行的公开压力测试被视为**转折点**之一——
它量化了资本缺口，使私人资本愿意重新进入。""")

R['tranche'] = (
"""分层(tranche) 指**把资产池的现金流按优先级切分为不同档**的结构安排，
是证券化（见 securitization）与 CDO（见 collateralized-debt-obligation）
的核心技术。
**基本结构**：
**优先级**先受偿、收益率最低、评级最高；
**中间级**次之；**次级（equity）** 最后受偿、
吸收最初的损失、收益率最高。
**它的实质**：**把同一资产池的风险在投资者之间重新分配**——
不是消灭风险，而是**决定谁先承担损失**。
**分层为什么"看起来"能创造高评级**：
若资产池的违约**相互独立**，
则只有在大量同时违约时优先级才会受损，
因此优先级可以获得远高于资产池平均质量的评级。
**这正是问题所在（危机中的核心失效）**：
**相关性假设是关键且脆弱的**——
在房价全国性下跌时，
底层按揭**同时违约**，
次级被迅速击穿后**优先级同样受损**；
分层所提供的保护在极端情形下**几乎消失**。
**与危机的关系**：
①**"按历史相关性校准的模型"低估了尾部风险**；
②**CDO²**（把 CDO 的中间级再分层打包）
使风险高度叠加、最终持有人难以辨识底层资产；
③**评级机构对分层证券的评级**
成了投资者判断的主要依据（见 credit-rating）。
**一句话概括：分层能切分风险，但不能降低系统性风险。**""")

R['comparative-advantage'] = (
"""比较优势(comparative advantage) 是李嘉图提出的贸易理论核心：
**即使一国在所有产品上的生产效率都低于他国，
双方仍可通过专业化与交换而共同获益**——
关键在于**相对成本**，而非绝对成本。
**经典例子**：两国都生产葡萄酒与布，
一国的效率在两者上都更高，
但只要它在某一产品上的**相对优势**更大，
专业化该产品并交换即可双赢。
**它的政策含义是自由的理论基础**（见 free-trade）：
贸易的收益来自**机会成本**（见 opportunity-cost）的差异，
因此"保护本国所有产业"会同时放弃这些收益。
**必须知道的四点限制**：
①**它是静态分析**——不考虑技术变迁、
规模经济与 learning by doing
（这些可能使"暂时保护"有理由，即幼稚产业论）；
②**收益的分配与总量无关**——贸易提高总产出，
但**受损者可能集中且得不到补偿**；
③**它假设要素可在国内自由流动**——现实中调整有成本与摩擦；
④**它不保证"不受冲击"**——高度专业化会提高对外部需求波动的暴露。
**与危机的关系**：
①**专业化提高了相互依赖**——供应链中断会跨境传导；
②**它解释了为何贸易战两败俱伤**——
双方都放弃了比较优势的收益（见 beggar-thy-neighbour）；
③**"相对优势"的判断会随技术与成本变化而改变**，
因此贸易格局的调整本身就会产生政治压力。""")

