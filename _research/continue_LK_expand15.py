R['fiscal-multiplier'] = (
"""财政乘数(fiscal multiplier) 衡量**政府支出或减税每增加一元，
最终使总产出增加多少**——
乘数大于 1 表示"一元支出带动超过一元的产出"。
**它为什么可能大于 1（机制）**：
政府支出成为某些人的收入 → 他们消费一部分 →
成为另一些人的收入 → 再消费一部分——
**逐轮递减的支出形成总需求的累积扩张**。
**乘数大小的关键决定因素**：
①**家庭是否受流动性约束**——若人们拿到钱就会花掉（因为借不到钱），乘数大；
②**经济是否有闲置产能**——若资源已充分利用，
支出只会推高物价（挤出，见 crowding-out）；
③**货币政策是否配合**——若央行不收紧，利率不上升，乘数大；
④**进口漏出**——支出用于进口则不产生国内收入；
⑤**自动稳定器**（见 automatic-stabilizer）会削弱乘数
（因为税收与救济随收入自动变动）。
**争议的核心是"衰退中乘数有多大"**：
**支持财政刺激者**引用实证研究称衰退中乘数可达 1.5 以上；
**怀疑者**指出估计方法敏感、且乘数在**高债务国家更小**
（因为市场信心与利率反应）。
**与危机的关系**：
**乘数的估计直接决定紧缩（见 austerity）的代价**——
若乘数被低估（如 IMF 在欧元区危机初期的判断），
紧缩造成的产出损失会远超预期。""")

