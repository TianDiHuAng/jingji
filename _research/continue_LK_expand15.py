R['basel-accords'] = (
"""巴塞尔银行监管委员会(BCBS) 是**各国银行监管机构组成的标准制定机构**，
**1974 年**由十国集团央行行长设立，秘书处设在 BIS。
**它的性质**：**不具超国家强制力**——
其标准通过各国立法转化为国内规则，
执行的差异因此长期存在（这也是其评估报告关注的重点）。
**三个版本的资本框架（见 capital-adequacy）**：
**Basel I（1988）**——确立 **8% 的最低资本充足率**与简单的风险权重分类；
**Basel II（2004）**——引入**内部评级法**与三大支柱
（最低资本、监管审查、市场纪律）；
**Basel III（2010 年后）**——大幅提高**核心一级资本**要求、
新增**杠杆率**（见 leverage）与**流动性指标**
（LCR 与 NSFR，见 liquidity-coverage-ratio）、
以及**逆周期缓冲**（见 countercyclical-capital-buffer）。
**它的核心权衡（这解释了为何标准不断修订）**：
①**风险敏感性 vs 简单可比**——内部模型更敏感，但**可被操纵**；
标准法简单，但会误配风险；
②**资本要求 vs 信贷供给**——更高要求提高安全性，
但可能抑制信贷（见 procyclicality）。
**与危机的关系**：
**Basel II 被广泛批评为助长了危机**——
内部评级法使按揭证券获得低权重、
资本要求顺周期、
且**完全没有覆盖流动性与表外风险**
（见 off-balance-sheet）。
**Basel III 正是对这些缺口的回应。**""")

R['basel-iii'] = (
"""巴塞尔III(Basel III) 是 **2010 年后**推出的**银行监管改革框架**，
是对 2008 年危机的直接回应。
**四项主要变化（每一项都对应一个危机教训）**：
①**提高资本质量与数量**——
核心一级资本（普通股与留存收益）要求大幅上升，
并设**资本留存缓冲**；
对应教训：危机前资本中大量是**无法吸收损失的**次级债。
②**新增杠杆率**——不按风险权重计算的简单上限；
对应教训：**风险权重可被模型调低**，
资本充足率"看起来达标而实际脆弱"（见 rwa）。
③**新增流动性要求**——**LCR**（30 天压力下的现金流覆盖）
与 **NSFR**（一年期的结构性资金匹配），
见 liquidity-coverage-ratio；
对应教训：**资本充足的银行也会因流动性枯竭而倒下**。
④**逆周期与系统重要性附加要求**——
逆周期资本缓冲（见 countercyclical-capital-buffer）、
G-SIB 附加损失吸收能力（见 sifi）。
**它的争议**：
①**顺周期效应**——更高的资本要求在经济下行时收紧信贷
（因此设计了"缓冲可释放"的机制）；
②**实施的不一致**——各国落地进度与细节差异显著，
形成**监管套利**空间（见 regulatory-arbitrage）；
③**成本与收益的估算有分歧**——学界对"更高的资本要求
是否显著降低增长"结论不一。
**本库的处理**：记录规则内容与争议，不评价具体数值是否恰当。""")

R['financial-crisis'] = (
"""金融危机(financial crisis) 是一个**总论性概念**，
指**金融体系出现严重功能紊乱**、
以致中介、支付或资源配置能力受损的情形。
**四种常见类型（本库据此分类案例）**：
**银行危机**——挤兑、倒闭与信贷收缩（见 bank-run、credit-crunch）；
**货币危机**——汇率崩溃、储备耗尽（见 currency-crisis）；
**债务危机**——主权或私人部门无法偿付（见 sovereign-default）；
**泡沫破裂**——资产价格崩溃（见 speculative-bubble）。
**它们常同时出现**（"**双危机**"，见 twin-crises），
且**相互强化**：货币贬值加重外币债务 →
主权风险上升 → 银行持有国债受损 → 需要救助 → 财政恶化。
**危机的共同机制（跨时代的规律）**：
①**杠杆与期限转换**（见 leverage、fractional-reserve）；
②**信息不对称导致的信任崩塌**（见 information-asymmetry）；
③**自我实现的预期**（见 self-fulfilling）；
④**顺周期的放大机制**（见 procyclicality、financial-accelerator）；
⑤**政策空间有限**（零利率、财政约束）。
**本库的立场（重要）**：
**记录机制与可核查的事实，并列不同解释，不作预测**。
因为危机史反复显示：**"这次不一样"综合征**
（认为本轮繁荣有特殊理由因而不可能崩盘）
是每一轮危机的共同前奏。""")

R['fiscal-space'] = (
"""财政空间(fiscal space) 指**政府在不危及债务可持续性或市场信心的前提下，
还有多少余地扩大支出或减税**。
**它与"债务水平"相关但不等同**——
同样的债务/GDP，财政空间可以差别很大，
取决于：**债务的币种结构**（本币 vs 外币，
见 original-sin）、**期限结构**、**利率水平与增长率之差**、
**国内储蓄与本国投资者基础**、以及**央行可信度**。
**它的判断没有唯一指标**：
常用的参考包括债务/GDP、利息支出占收入比、
以及**市场融资成本对赤字的反应**。
**与危机的关系极为直接**：
①**危机恰恰是最需要财政扩张的时候**（货币政策可能已用尽，
见 liquidity-trap），**而财政空间可能已被和平时期消耗**；
②**危机本身会压缩财政空间**——救助银行、失业救济、
税收下降同时发生，债务骤升；
③**"空间"部分取决于信心**——若市场相信政府会整顿，
短期赤字不会立即推高融资成本（这使"空间"有自我实现的成分）。
**一个必须警惕的循环**：
**财政空间不足 → 被迫紧缩 → 增长下降 → 债务比率上升 → 空间更小**
（这就是欧元区危机中若干国家的经历，见 austerity）。
**因此"危机前保留空间"本身是一种审慎。**""")

R['lewis-turning-point'] = (
"""刘易斯拐点(Lewis turning point) 指**二元经济中
"无限供给的剩余劳动力"被吸收完毕**的时点，
由刘易斯的发展模型提出。
**模型的图景**：
传统农业部门存在大量**边际生产率极低的剩余劳动力**，
现代部门可以**在不变的低工资水平上无限吸纳**他们；
因此经济增长伴随**工资长期平稳**、利润占比上升、储蓄与投资扩张。
**拐点的含义**：
一旦剩余劳动力耗尽，**工资开始快速上涨**——
增长模式必须从"**要素投入驱动**"转向"**生产率驱动**"。
**它的政策与危机含义**：
①**通胀压力上升**——工资上涨推高成本，
若生产率未同步提升，则形成**结构性通胀**
（这对依赖低成本出口的模式构成挑战）；
②**收入分配改善**——劳动份额上升，
但企业利润率受压；
③**增长放缓是正常的**——这是**收敛**（见 convergence）的表现，
而非"陷阱"（见 middle-income-trap）；
④**资产价格与债务**——工资上涨期的房地产与信贷扩张
是许多经济体的风险来源。
**必须注意的争议**：
**拐点的测量极不精确**——"剩余劳动力"本身难以界定，
且不同研究者对同一国家的判断差异很大；
**因此它是有用的分析框架，不是可精确判断的时点。**""")

R['ppi'] = (
"""生产者价格指数(producer price index, PPI) 衡量
**生产者出售商品与服务的价格变化**，
与消费者价格指数（见 cpi 相关条目）相比，
它**位于产业链的更上游**。
**它与 CPI 的关系是理解通胀传导的关键**：
**PPI 通常是 CPI 的领先指标**——
上游的能源、原材料与中间品涨价，
会在一段时间后传导到最终消费品；
**但传导并不完全**：
①**企业可能压缩利润吸收成本**而非提价（取决于竞争与需求强弱）；
②**服务价格与工资的传导更慢**；
③**汇率升值可抵消进口投入的涨价**。
**因此"PPI 大涨但 CPI 温和"并不矛盾**——
它反映的是"**传导受阻**"，而这一状态本身难以持续
（要么成本转嫁出去，要么利润被压缩导致投资与就业下降）。
**与危机的关系**：
①**2021—22 年**的经历是典型例证——
能源与大宗商品推动 PPI 大幅上升，
CPI 起初反应温和，随后因传导与需求强劲而跟上；
②**PPI 的持续下跌**（如 2010 年代中期部分经济体）
通常反映**产能过剩与需求不足**，
是通缩压力（见 deflation）的先行信号；
③**它用于平减 GDP 与核算实际产出**，因此其准确性影响其他统计。""")

