R['black-scholes'] = (
"""布莱克-斯科尔斯模型(Black-Scholes model) 是**期权定价**的基础模型，
给出了**欧式期权的理论价格**。
**它的核心洞见**：
通过**连续调整标的资产与无风险资产的组合**，
可以**复制期权的收益**——
因此期权的价格必须等于复制组合的成本，
**否则存在无风险套利**（见 arbitrage）。
这一"**无套利**"逻辑是现代金融工程的基石。
**它的五个输入**：
标的现价、行权价、到期时间、无风险利率、
以及**波动率**——
**前四个可观测，波动率不可观测**，
因此"**隐含波动率**"成为市场对未来的预期度量。
**它的关键假设（也是局限）**：
①**波动率恒定**——而现实中波动率会聚集与跳变
（"**波动率微笑**"即是对该假设的偏离）；
②**价格连续、无跳跃**——而危机中价格会跳空；
③**可以连续对冲**——而流动性枯竭时无法调整；
④**无交易成本与无摩擦**。
**与危机的关系**：
①**它使期权市场快速发展**，
但也**给了使用者"精确"的错觉**——
模型在小概率大幅波动时系统性出错；
②**基于该模型的动态对冲在危机中失效**——
相关性上升、流动性消失，对冲无法执行；
③**1997 年诺贝尔奖、1998 年 LTCM 崩盘**的对照
常被引用：**理论的精确不等于风险的消除**。""")

