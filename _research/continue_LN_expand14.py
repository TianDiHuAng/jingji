R['twin-crises'] = (
"""双危机(twin crises) 指**银行危机与货币危机同时发生、
并相互强化**的现象，由卡明斯基与莱因哈特系统研究。
**为什么两者会同时出现（机制）**：
①**银行体系持有大量外币负债**——
本币贬值使其资产负债表恶化，
银行陷入困境（见 original-sin、currency-mismatch）；
②**央行的两难**——
为保卫汇率需**提高利率**，
而高利率会**加深银行的困境**（借款人违约上升、
银行融资成本上升）；
③**救助银行需财政资源**——
若财政也依赖外部融资，则主权风险上升，
形成"**银行—主权**"的循环（见 sovereign-risk）；
④**资本外流同时冲击两者**——
银行失去外部融资，货币承受贬值压力。
**这解释了一个重要的政策困境**：
**在双危机中，汇率与银行体系不能分别拯救**——
保卫汇率会压垮银行，救银行会耗尽储备。
**与危机的关系**：
**1990 年代的新兴市场危机大多是双危机**
（墨西哥 1994、东亚 1997、阿根廷 2001、土耳其 2001），
这也是它们比单纯的货币危机或银行危机**更深更久**的原因。
**政策含义**：
①**事前的预防更有效**——
限制外币借款、提高资本与流动性缓冲、
以及避免汇率严重高估；
②**事后的次序很重要**——
先稳定银行体系再处理汇率，或相反，
可能导致完全不同的结果。""")

R['carry-trade'] = (
"""套利交易(carry trade) 指**借入低利率货币、投资于高利率资产**，
以赚取利差（"carry"）的策略。
**它的收益结构是不对称的**：
**平时**——稳定的利差收入，波动小、看起来"低风险"；
**危机时**——高息货币暴跌、低息货币飙升，
**一次冲击可能抹去数年的利差收益**
（"**捡钢镚在压路机前**"的典型）。
**为什么它长期存在**：
①**利差是真实的**（利率差异）；
②**汇率通常不会立即调整**——
短期内汇率的波动小于利差，
这使 carry 在多数月份盈利；
③**杠杆放大收益**（见 leverage）。
**与危机的关系极为具体**：
①**carry trade 的平仓是危机传染的重要渠道**——
当风险偏好下降，投资者同时撤出高息货币，
造成"**拥挤交易的踩踏**"；
②**它是"突然停止"（见 sudden-stop）的微观机制之一**——
资本流入的很大部分是由利差驱动的短期资金；
③**日元 carry trade 的规模与平仓**
多次被视为全球市场波动的放大器
（低利率日元是长期的主要融资货币）；
④**它使"利差交易看起来像套利"**——
而实际上是**承担了尾部风险的投机**（见 speculation）。
**一个关键的分辨**：
**carry 的长期平均收益为正，但这不意味着它是"免费午餐"**——
它是**对承担崩盘风险的补偿**。""")

R['cbdc'] = (
"""中央银行数字货币(central bank digital currency, CBDC) 指
**由央行发行的数字形式的法定货币**，
是央行负债的直接数字化（与商业银行存款不同）。
**它与现有支付工具的区别**：
**银行存款**是商业银行的负债（有信用风险，但有存款保险）；
**现金**是央行负债（无信用风险，但仅限实物）；
**CBDC** 也是央行负债，但是**数字的、可编程的、可追溯的**。
**它的潜在收益**：
①**支付效率与普惠**——降低跨境与零售支付成本；
②**货币政策的传导**——理论上可提高直达性；
③**对抗私人稳定币**（见 stablecoin）对货币主权的侵蚀。
**它的核心风险（这是争论的焦点）**：
①**银行脱媒**——若公众可直接持有央行数字货币，
危机时存款会迅速转向 CBDC，
**加速银行挤兑**（见 bank-run）；
②**隐私与监控**——可追溯性带来隐私问题；
③**金融体系结构的改变**——商业银行的融资基础可能被削弱；
④**跨境溢出**——影响他国货币主权与资本流动。
**因此各国的设计普遍采取"限制"**：
**不计息**（避免与存款竞争）、**持有上限**、
以及**通过商业银行间接分发**（双层运营）。
**与危机的关系**：
**它可能改变挤兑的速度与形态**——
数字形式的提款比排队取现快得多，
这使"**暂停兑换**"（如银行假日，见 bank-holiday）
这一传统工具的有效性下降。
**本库的处理**：记录设计与争议，不预测任何国家的发行结果。""")

