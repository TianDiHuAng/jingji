R['interest-rate-swap'] = (
"""利率互换(interest rate swap) 是**双方约定交换固定利率与浮动利率支付**的合约，
通常一方支付固定、收取浮动，另一方相反。
**它的用途是"改变利率风险的性质"**：
①**企业或银行**可将浮动利率负债转为固定（锁定成本），
或反之（在预期降息时降低成本）；
②**金融机构**用它调整资产负债的**利率敏感性**（见 alm）；
③**投机者**用它表达对利率路径的看法。
**它与"利率期货"的区别**：
期货是标准化的交易所合约（见 futures）；
**利率互换是场外的定制合约**（见 otc），
因此承担**对手方风险**（见 counterparty-risk）。
**关键机制是"净额结算"**（见 netting）：
双方只交换利息差额，本金不交换，
因此**信用敞口远小于名义本金**——
这是理解"互换市场规模巨大但风险相对可控"的关键。
**与危机的关系**：
①**它是全球名义金额最大的衍生品类别**，
其网络与不透明在危机中受到关注；
②**危机后标准化互换转向中央清算**
（见 central-counterparty），以降低双边敞口；
③**互换利差**（如 swap spread）是市场压力的重要指标——
它与国债收益率之差反映了**对手方风险与流动性溢价**；
**2008 年该利差的异常扩大**是银行互不信任的直接反映。""")

R['solow-model'] = (
"""索洛-斯旺模型(Solow-Swan model) 是**新古典增长模型**的基本框架，
解释**资本积累、人口增长与技术进步如何决定长期产出**。
**它的核心机制是"资本边际报酬递减"**：
资本存量增加会提高产出，但**每一单位新增资本的产出递减**；
同时**折旧会侵蚀资本**——
因此经济会收敛到"**稳态**"：
**投资恰好补偿折旧与人口增长所需的资本**，
此时人均资本不再变化。
**它的三个关键结论**：
①**长期人均增长的唯一来源是技术进步**（见 total-factor-productivity）——
单纯增加储蓄只会提高人均资本的**水平**，
不能持续提高**增长率**（这是"**收敛**"的机制，见 convergence）；
②**储蓄率提高会提高稳态收入水平**，但不改变长期增长率；
③**穷国应比富国增长更快**（因资本边际报酬更高）——
这就是"条件收敛"。
**它的局限**：
把技术视为**外生**（模型不解释技术进步从何而来），
这催生了内生增长理论；
**它也没有金融部门**，因此不涉及危机。
**与危机的关系**：
①**它是"危机后潜在产出下移"的理论背景**——
资本存量受损会降低稳态收入；
②**它解释了为何"提高储蓄率"不是万能的**——
若技术不进步，储蓄只会带来更多资本而非更高增长。""")

R['natural-rate-unemployment'] = (
"""自然失业率(natural rate of unemployment) 指**在不存在周期性因素时，
经济中仍然存在的失业率**，
由**摩擦性**（换工作的空档）与**结构性**（技能与岗位不匹配）因素构成。
**它与 NAIRU**（见 nairu）**的关系**：
两者常被混用，但严格说——
**自然失业率**是长期均衡概念；
**NAIRU** 是"通胀稳定时的失业率"，可随预期与制度移动。
**它的决定因素**：
劳动力市场的制度（雇佣保护、最低工资、失业保险的慷慨程度）、
技能匹配的效率、地理流动性、以及人口结构。
**为什么它重要**：
它是判断"**是否充分就业**"的基准——
若实际失业率低于自然率，通胀压力会上升。
**但它的测量极不精确**：
**不可直接观测**，只能估计，
而估计方法（如菲利普斯曲线的拟合）对样本期极敏感，
**不同研究的差异可以很大**。
**与危机的关系**：
①**危机会推高自然失业率**——长期失业者的技能退化、
雇主对其的负面筛选，形成"**滞后效应**"，
使"潜在就业水平"本身下降；
②**这意味着"危机后失业率回到危机前水平"未必等于"恢复"**——
基准可能已经移动；
③**政策含义**：
若把结构性失业误判为周期性，
会过度刺激；反之则会让失业固化。""")

