R['laffer-curve'] = (
"""拉弗曲线(Laffer curve) 描述**税率与税收收入之间的关系**：
税率从 0 上升时税收增加，
但超过某一点后，**税率继续上升会使税收下降**——
因为逃税、避税与减少生产（或减少应税活动）随之增加。
**因此它呈倒 U 形，两端（0% 与 100%）的税收均为零**。
**它的正确部分**：
①**极端税率会损害税基**——这一点没有争议；
②**税率影响行为**（劳动、投资、申报）——
这是税收经济学的标准结论。
**它常被误用的部分（必须说清）**：
①**"减税能增加税收"并不普遍成立**——
它只在税率已处于**下降段**时成立，
而对多数国家的主要税种，实际税率远未到达那一点；
②**最优税率的位置无法由理论确定**——
它依赖具体的弹性估计，而这些估计差异很大；
③**它被用作政治论证**（"减税自偿"）时，
往往**忽略了过渡期的赤字**。
**与危机的关系**：
它主要影响**长期财政政策与供给侧改革**（见 supply-side），
而非危机应对；
但在**高债务国家**，"减税能否自偿"的判断
直接决定财政可持续性的评估，
因此与**财政空间**（见 fiscal-space）的讨论相关。
**本库的处理**：记录该曲线的逻辑与常见误用，不评价具体税率政策。""")

R['yield-curve-control'] = (
"""收益率曲线控制(yield curve control, YCC) 指**央行承诺把特定期限的国债收益率
锁定在某个目标水平**，并**无限量购买**以实现该目标。
**它与量化宽松（见 quantitative-easing）的关键区别**：
**QE 承诺的是"数量"**（买多少），
**YCC 承诺的是"价格"**（收益率不超过某水平）——
后者是**更强的承诺**，因为它放弃了对自己资产负债表规模的控制。
**它的实践**：
**日本央行（2016 年起）**是主要使用者，
把十年期国债收益率引导至零附近；
**澳大利亚（2020—2021）**曾对三年期收益率设目标，
后在压力下放弃。
**它的优势**：
①**直接作用于长端利率**，比 QE 更精确；
②**减少购债规模的不确定性**（不必不断扩大资产负债表）；
③在**零利率下限**（见 liquidity-trap）下扩展了政策空间。
**它的风险（这是最重要的部分）**：
①**"可退出性"问题**——一旦市场测试目标水平，
央行要么无限购买（失去控制），要么放弃（失去信誉）；
**澳大利亚 2021 年的经历正是后者**；
②**市场功能受损**——央行成为某期限的支配性买家，
价格发现功能被削弱；
③**财政主导的嫌疑**——为政府债务设定利率上限
（见 fiscal-dominance）。
**一句话概括**：**YCC 是用"承诺"换"控制"**，
而承诺一旦被质疑，代价很高。""")

R['aggregate-demand'] = (
"""总需求(aggregate demand) 指**在给定价格水平下，
经济中对最终产品与服务的需求总量**，
由**消费、投资、政府支出与净出口**四部分组成。
**它与总供给（见 aggregate-supply）的相互作用决定产出与物价**：
**需求不足** → 产出下降、失业上升（这是凯恩斯式衰退）；
**需求过旺** → 物价上涨（若产能已满）；
**供给收缩** → 物价上涨且产出下降（滞胀，见 stagflation）。
**为什么"总需求不足"可能持续存在（凯恩斯的核心论点）**：
①**流动性偏好**（见 liquidity-preference）使储蓄未必转化为投资；
②**工资与价格粘性**（见 sticky-prices）使调整缓慢；
③**预期的自我实现**（见 self-fulfilling）使悲观延续；
④**资产负债表效应**（见 balance-sheet-recession）使主体主动偿债而非支出。
**政策含义**：
这是**财政与货币政策的理论依据**；
而在**零利率 + 资产负债表衰退**的组合下，
**只能靠财政**（见 fiscal-multiplier）。
**与危机的关系**：
**危机本质上是总需求的骤降**，
而金融体系的损伤使这一骤降被放大与延长
（见 financial-accelerator、credit-crunch）。
**一个必要的平衡**：
在**供给受限**的经济中（如产能瓶颈、劳动力短缺），
扩张需求只会推高物价——
**因此"需求不足"与"供给不足"的区分是政策的第一道判断**。""")

R['dutch-disease'] = (
"""荷兰病(Dutch disease) 指**资源出口（或大量资本流入）
导致本币升值或国内成本上升，
从而削弱其他可贸易部门竞争力**的现象，
得名于荷兰发现天然气后的经历。
**机制链条清晰**：
资源出口带来外汇收入 → 本币升值（或国内工资与物价上涨）→
**制造业与农业出口竞争力下降** → 这些部门萎缩 →
经济对资源的依赖加深。
**"去工业化"是其典型后果**，
而这一过程往往是**不可逆的**——
一旦产业链与技能流失，即使资源价格回落也难以恢复。
**三种传导渠道**：
**汇率渠道**（最常被提及）、
**支出渠道**（资源收入推高国内需求与价格）、
以及**要素流动渠道**（劳动力与资本流向资源部门）。
**与危机的关系极为直接**：
①**资源型经济体的财政与出口高度集中于单一商品**，
价格下跌时**收入与偿债能力同时恶化**
（见 twin-crises、resource-curse）；
②**繁荣期的信贷扩张与资产泡沫**是由此衍生的风险；
③**"预防性"的做法**是设立**主权财富基金**
（见 sovereign-wealth-fund）把收入转化为外部资产，
从而**隔离汇率与支出的冲击**——挪威是常被引用的正面案例。
**一个必要的分辨**：
荷兰病描述的是**结构性机制**，
而"资源诅咒"（见 resource-curse）是**更宽泛的经验假说**
（含制度与治理因素）。""")

R['efficient-market'] = (
"""有效市场假说(efficient market hypothesis, EMH) 主张
**资产价格已反映所有可得信息**，因此**无法持续获得超额收益**。
**三种形式（按信息范围递增）**：
**弱式**——价格反映历史价格与交易量（技术分析无效）；
**半强式**——价格反映所有公开信息（基本面分析无效）；
**强式**——价格反映所有信息，包括内部信息
（这显然不成立，否则内幕交易无法获利）。
**它的理论价值**：
①为**无套利定价**提供基础；
②解释了为何**多数主动管理难以持续跑赢指数**；
③强调了**套利对错价的纠正作用**（见 arbitrage）。
**它的局限（危机后尤为突出）**：
①**套利有限**——纠正错价需要资金与耐心，
而危机中两者都消失（"**套利限制**"）；
②**无法解释泡沫与崩盘**——若价格已反映基本面，
为何会出现持续的、幅度巨大的偏离？
③**行为偏差是系统性的**（见 behavioral-finance），
而非随机噪声；
④**"价格正确"与"价格稳定"是两回事**——
即使价格平均是正确的，其波动也可能远超基本面变化。
**与本库的关系**：
**EMH 是理解危机时必须处理的一个论点**——
它的强式版本被危机证伪，
但**弱式与半强式仍有相当支持**；
**把它当作"市场永远正确"是误解，当作"完全无用"也是误解**。""")

