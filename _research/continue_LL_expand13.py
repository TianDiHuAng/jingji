R['lucas-critique'] = (
"""卢卡斯批判(Lucas critique) 是卢卡斯提出的方法论批评：
**用历史数据估计的经济关系，在政策规则改变后会失效**，
因为**人们的预期与行为会随政策规则改变而改变**。
**论证的逻辑**：
计量模型估计的是"在既有政策环境下"的行为参数；
但当政策改变时，**理性的经济主体会重新调整预期**，
于是这些"参数"本身发生变化——
**因此不能用旧参数预测新政策的效果**。
**一个经典例子**：
历史上"通胀与失业的替代关系"（菲利普斯曲线，见 phillips-curve）
是在特定货币政策环境下观察到的；
当央行改为反通胀的规则后，这一关系**消失了**
（1970 年代的滞胀即是明证）。
**它的深远影响**：
①**宏观模型必须建立在微观基础之上**——
即从个体最优化出发，而非直接拟合总量关系；
②**政策评估必须考虑预期反应**
（这催生了"政策模拟"与"前瞻性模型"）；
③**它强化了"规则 vs 相机抉择"的讨论**——
若政策可被预期，其效果会被抵消（见 rational-expectations）。
**与危机的关系**：
该批判对**监管**同样适用——
**用危机前的数据校准的模型，无法预测新的金融结构下的风险**；
这也是压力测试（见 stress-test）情景设计困难的根源：
**它必须想象"从未发生过的情形"**。""")

