R['gold-reserve-act-1934'] = (
"""美国黄金储备法(Gold Reserve Act) 于 **1934 年 1 月 30 日**通过，
要求**联邦储备体系持有的全部黄金与金券上交、
所有权归美国财政部**。
**它的三项核心内容（据来源）**：
①**禁止财政部与金融机构以美元纸币兑换黄金**；
②**设立"外汇稳定基金"(ESF)**，由财政部控制，
**可在不经美联储协助或批准的情况下调控美元价值**；
③**授权总统以公告方式确定美元的黄金价值**。
**它与此前的行政命令配套**：
一年前（**1933 年**）的**第 6102 号行政命令**
已使美国公民在全世界拥有或交易黄金成为刑事犯罪
（部分首饰与收藏币除外）。
**法案通过后的关键动作**：
罗斯福**立即把黄金的法定价格从每金衡盎司 20.67 美元改为 35 美元**——
这一提价**激励全球金矿扩大生产、外国把黄金运往美国**，
同时**通过推高通胀使美元贬值**；
黄金储备增加**扩大了货币供应、降低了实际利率**，
进而**增加了对耐用品的投资**。
**后续（来源记载）**：
私人持有黄金的限制**于 1974 年经《国际开发协会拨款法》附加条款废除**
（福特总统 1974 年 8 月 14 日签署，1974 年 12 月 31 日生效）。
**与危机的关系**：
它是"**通过货币贬值与贵金属重估来对抗通缩**"的政策实验——
**提高金价 = 增加货币基数**，是 1930 年代"再通胀"的关键一步；
而**外汇稳定基金的设立**则把汇率干预权集中到了财政部，
这一制度安排延续至今。""")

