R['quantity-theory-money'] = (
"""货币数量论(quantity theory of money) 主张**物价水平与货币数量成正比**，
其经典表述是**交换方程**：**MV = PY**
（M 货币量、V 流通速度（见 velocity-of-money）、
P 物价、Y 实际产出）。
**两种读法，差别重大**：
**弱式**——如果 V 与 Y 稳定，则 M 的变动会反映在 P 上；
**强式**（货币主义的核心）——**V 与 Y 长期不受 M 影响**，
因此 M 的变动会一对一地转化为物价变动。
**关键的经验困难**：
①**V 并不稳定**——危机中 V 骤降，
使 M 大增而 P 不涨（见 liquidity-trap）；
②**Y 在短期会受影响**——这正是凯恩斯主义的批评：
货币扩张可以先提高产出与就业，而不只是物价；
③**"因果方向"受质疑**——也可能物价上涨导致货币需求增加。
**它在历史上的成功与失败**：
**成功**——解释 16 世纪价格革命（见 price-revolution）、
以及长期恶性通胀（见 hyperinflation）；
**失败**——无法解释 2008 年后与 2020 年后的
"基础货币暴增而通胀温和"（直到 2021—22 年通胀才出现，
且被普遍归因于供给与财政因素）。
**这与本库的一条主线相关**：
**"印钞必然通胀"是一个条件命题，不是无条件规律**——
条件是货币进入支出、且产能受限。""")

R['rwa'] = (
"""风险加权资产(risk-weighted assets, RWA) 是**按信用与市场风险大小
对资产进行加权后得到的总额**，
用作**资本充足率（见 capital-adequacy）的分母**。
**加权的逻辑**：
不同资产的风险不同——
持有现金与本币主权债的风险极低（权重接近 0），
而无抵押企业贷款与结构性产品的风险较高（权重可高于 100%）。
**因此资本要求的真正含义是**：
"资本 / 风险加权资产 ≥ 某比率"，
即**每单位风险所对应的资本**。
**它为什么是危机的核心问题（这一点极为关键）**：
**权重由规则或模型决定，因此可以被"优化"**。
①**内部评级法**允许银行用自有模型估计风险，
这在提高敏感度的同时**给模型操纵留出空间**
（如低估违约概率与相关性）；
②**评级套利**——把资产包装成高评级证券，
权重随之下降（见 credit-enhancement）；
③**权重低估真实风险的历史案例**——
次贷危机前，按揭支持证券的权重很低，
银行的"资本充足率"看起来稳健，
**但其真实杠杆与尾部风险远高于报表所示**。
**这正是杠杆率被引入的理由**：
**杠杆率不以风险加权计算**，
因此**无法通过调低权重来规避**——
两者互补，缺一不可。""")

R['secondary-market'] = (
"""二级市场(secondary market) 指**已发行的证券在投资者之间转手交易**的市场，
与一级市场（见 primary-market）相对。
**关键区分**：**二级市场的交易不直接给发行方带来新资金**——
资金在投资者之间转移；发行方的融资发生在一级市场。
**但它对一级市场不可或缺**：**没有流动性，就没有人愿意在一级市场买入**——
投资者愿意为一笔"将来卖得掉"的资产支付更高价格。
**它的三项功能**：
①**流动性**——使长期资产可以被短期持有；
②**价格发现**——集中交易形成的价格成为估值基准；
③**治理约束**——股价与收购的可能对管理层形成压力。
**与危机的关系**：
①**二级市场的价格是抵押品估值的基准**——
价格剧烈波动会直接触发追加保证金与贱卖
（见 collateral、margin-call、fire-sale）；
②**"流动性错觉"**——
在平静期，投资者以为资产随时可以卖出，
因而压低了对流动性的定价；
危机中买卖价差骤宽（见 bid-ask），
**这种错觉同时消失**，造成"所有人同时想退出"；
③**二级市场的冻结会立即阻断一级市场**——
发行窗口关闭，依赖滚动融资的发行人（银行、房企）随之陷入困境。
**因此"市场流动性"不是技术细节，而是金融稳定的组成部分。**""")

R['spv'] = (
"""特殊目的实体(special purpose entity/vehicle, SPE/SPV) 是
**为特定交易目的设立的独立法律实体**，
常用于证券化（见 securitization）、项目融资与风险隔离。
**它解决的核心问题是"破产隔离"**：
把资产转移到 SPV 后，
即使发起机构破产，该资产也不进入其清算财产，
从而保护证券持有人的权益。
**因此它在结构上是功能性的，并非天然有问题**。
**但它也是危机的关键载体，原因有三**：
①**表外处理**——若 SPV 不被合并，
其资产与负债就不进入发起机构的资产负债表
（见 off-balance-sheet），
**杠杆与风险因此变得不可见**；
②**隐性担保与声誉风险**——
当 SPV 陷入困境时，发起机构往往不得不救助
（因为市场将其视为一体），
**风险于是"回到"表内**——2008 年多家银行即如此；
③**"孤儿 SPV"与治理真空**——
SPV 通常没有员工、没有实质经营，
其决策由发起方控制，**独立董事常常形同虚设**。
**监管回应**：
**合并规则收紧**（按实质控制判断是否并表）、
**风险加权覆盖表外敞口**、
以及**要求披露与发起机构的风险关联**。
**一个根本的教训**：
**法律形式上的隔离，不等于经济实质上的隔离**——
只要声誉与融资渠道相连，风险终会回流。""")

R['capm'] = (
"""资本资产定价模型(capital asset pricing model, CAPM) 是
**描述风险与预期回报关系**的基础模型，
其核心公式为：
**预期回报 = 无风险利率 + β × 市场风险溢价**。
**它的核心洞见**：
**只有系统性风险（不可分散的风险）应获得补偿**——
因为可分散的特质风险（见 diversification）
投资者可以自己消除，市场不会为此付费。
**β（见 beta）因此成为风险的唯一度量**。
**它的前提假设（也是它的局限）**：
①投资者只关心均值与方差；
②可以无风险利率无限借贷；
③市场组合包含所有资产；
④无交易成本与税收；
⑤预期一致（同质预期）。
**这些假设在现实中全都不成立**，
因此 CAPM 的经验检验结果不佳——
**"低波动异象"**（低 β 股票长期回报反而偏高）
是对它最直接的挑战。
**与危机的关系**：
①**危机中"所有相关性都变成 1"**，
β 的分散化前提失效，
基于 β 的风险预算与对冲策略同时失灵；
②**它是"风险预算"与"业绩归因"的通用语言**，
因此即使理论上不完善，仍被广泛使用——
**这本身构成一种风险：用错模型的人越多，错得越一致**；
③**它的简化使"尾部风险"被系统性低估**。""")

R['central-counterparty'] = (
"""中央对手方(central counterparty, CCP) 指**在交易双方之间介入、
成为每个卖方的买方与每个买方的卖方**的清算机构。
**它如何降低风险**：
通过**合约更替**(novation)，
原本的双边信用敞口被替换为**对 CCP 的敞口**——
而 CCP 通过**多边净额结算**（见 netting）、
**每日盯市**与**保证金**（见 margin-call）
把敞口压到很小。
**因此它大幅降低了对手方风险**（见 counterparty-risk）。
**但它同时制造了新的集中风险——这是危机后最重要的争论**：
①**"单点故障"**——若 CCP 本身失败，
所有参与者同时受损，后果比任何单一机构倒闭更严重；
②**风险相互依赖**——CCP 的会员高度重叠，
一家会员违约可能同时冲击多家 CCP；
③**"相互连接的 CCP"**——同一会员在不同 CCP 的敞口相互关联，
而各 CCP 之间缺乏协调；
④**保证金在压力下会顺周期上升**，
迫使会员抛售资产（见 procyclicality）。
**监管回应**：
对 CCP 施加更高的资本与流动性要求、
**恢复与处置计划**（"**生前遗嘱**"）、
以及跨境监管协调（因为 CCP 的业务是跨法域的）。
**一个必要的分辨**：
**CCP 把"双边信用风险"转换成了"集中与操作风险"**——
风险没有消失，而是换了形态。
**这使"清算所太大而不能倒"成为新的政策难题。**""")

R['financial-innovation'] = (
"""金融创新(financial innovation) 指**新的金融产品、工具、机构与流程的出现**，
如证券化（见 securitization）、衍生品、货币市场基金、
以及近年的加密资产与去中心化金融。
**它的正当功能**：
①**风险分担**——把风险转移给更有能力承担的一方；
②**降低交易成本**——减少搜寻与匹配成本（见 transaction-cost）；
③**提高流动性**——把不可交易的资产（按揭）转化为可交易证券；
④**满足真实的定制需求**（企业的套保、投资者的期限偏好）。
**但它有三条通向危机的路径（这是关键）**：
①**信息不对称加剧**——产品越复杂，
投资者越难评估其真实风险，
**评级与模型于是取代了独立判断**；
②**监管套利**——创新常常发生在监管边界之外，
**而规则总是滞后于产品**（见 regulatory-arbitrage）；
③**杠杆与不透明**——创新可能把风险转移到
**不受监管、没有最后贷款人、也没有处置框架**的角落
（影子银行，见 shadow-banking）。
**一个重要的历史观察**：
**危机前的创新往往以"这次风险被更好地分散了"为叙事**——
2000 年代的结构化产品正是如此，
而实际上**风险被集中到了少数机构的资产负债表上**。
**因此对金融创新的评价必须区分**：
**它是否真正转移了风险，还是仅仅转移了风险的可见性**。""")

