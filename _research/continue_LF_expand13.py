R['deleveraging'] = (
"""去杠杆(deleveraging) 指**降低债务水平相对于收入或资产的比例**的过程。
**它可以通过三条路径实现**：
①**偿债**——用收入偿还债务（紧缩支出）；
②**违约与减记**——债务被核销（见 debt-restructuring）；
③**通胀**——名义债务不变而名义收入上升，比率自动下降
（这是"**通过通胀去杠杆**"）。
**为什么去杠杆通常伴随衰退**：
**所有人的收入都是别人的支出**——
当家庭、企业与政府同时削减支出以偿债时，
总收入下降，债务比率反而可能**上升**。
这是"**去杠杆悖论**"：个体理性导致集体困境。
**明斯基与后来的研究区分了两种去杠杆**：
**"好"的去杠杆**——由经济增长驱动（分母变大）；
**"坏"的去杠杆**——由偿债与违约驱动（分子变小，但收入同时萎缩）。
**与危机的关系**：
①**危机后去杠杆是必然的**，但**路径选择决定了痛苦的分布**——
通胀损害债权人，违约损害债权人，
紧缩损害债务人与就业者；
②**金融机构的去杠杆会放大实体收缩**（见 credit-crunch），
因为它通过收缩信贷把压力传导出去；
③**这也是"资产负债表衰退"（见 balance-sheet-recession）
与"长期停滞"（见 secular-stagnation）假说的经验基础**。
**一个必要的分辨**：**降低杠杆率与"偿还债务"不是一回事**——
前者是比率，后者是行为。""")

