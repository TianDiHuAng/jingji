R['tripartite-1936'] = (
"""三方协定(Tripartite Agreement) 是**美国、法国与英国于 1936 年 9 月**
达成的**国际货币协定**，
目的是在**大萧条期间国际货币体系崩溃后，
稳定三国货币在国内与国际汇兑市场的价值**。
**背景（据来源）**：
大萧条期间，自由国家间的**国际货币合作瓦解**——
**英国 1931 年、美国 1933 年相继中止金本位**，
其货币与**金集团**国家（尤其法国）的货币之间出现严重失衡；
**美元与英镑贬值**提高了美英的进口价格、压低了其出口价格。
**协定的内容与性质**：
它是**非正式的、临时的**安排；
签字国承诺**避免竞争性贬值**（只要不严重妨碍国内繁荣），
并约定**按事先商定的价格、以卖方货币相互出售黄金**；
**法国据此贬值**；其余金集团国家**比利时、瑞士、荷兰**也加入。
**效果（来源的评价很明确）**：
**它稳定了汇率，终结了 1931—1936 年的货币战**，
**但未能帮助世界贸易的复苏**。
**与危机的关系**：
①它是"**竞争性贬值（见 competitive-devaluation）如何收场**"的标准案例——
各国最终认识到相互贬值两败俱伤；
②它**只解决了汇率、未解决贸易与需求**——
**这正是它的局限**，也是战后建立更完整体系
（布雷顿森林、GATT）的理由；
③它是**国际合作"从无到有但仍不充分"的过渡形态**。""")

R['gold-bloc'] = (
"""金集团(gold bloc) 指**大萧条期间坚持金本位的七个国家**，
**以法国为首**，另含**比利时、卢森堡、荷兰、意大利、波兰与瑞士**。
**它的形成背景（据来源）**：
1931 年 5 月**奥地利最大商业银行 Creditanstalt 违约**，
冲击波及全欧，多国相继**放弃金本位**
（**英国 1931 年 9 月**，丹麦、挪威、瑞典亦在 9 月，
芬兰 10 月、日本 12 月）；
而金集团国家在 **1933 年伦敦国际经济会议**上**重申维持汇率稳定**——
当时包括美国与意大利在内已有 **35 国放弃金本位**。
**它们的政策选择及其代价**：
**坚持通缩性政策**——
"在放弃外汇管制的同时，**提高关税、收紧进口配额**，
以隔离本国经济并保护黄金储备"。
**结果**：
随着 1934 年美元贬值与英镑持续贬值，
金集团国家的**出口企业难以维持盈利**，
并遭遇**大规模资本外逃至美国**；
**比利时与卢森堡于 1935 年 3 月放弃金本位并贬值**；
**1936 年 9 月**三国签署三方协定（见 tripartite-1936）后，
**其余金集团国家最终全部放弃金本位**。
**一个关键的经验结论（来源引述）**：
《A Program for Monetary Reform》(1939) 的作者指出，
**1931 年即放弃金本位的斯堪的纳维亚国家，比金集团国家更早走出大萧条**。
**与危机的关系**：
它证明了"**坚持固定汇率 + 通缩调整**"在需求崩溃时的代价——
**越晚放弃，衰退越深**；
这直接影响了后来"浮动汇率 + 货币政策自主"的制度选择
（见 exchange-rate-regime、impossible-trinity）。""")

