es = {json.load(open(f, encoding='utf-8'))['id']: f for f in glob.glob('data/entries/*.json')}
n, sk = 0, []
for eid, txt in CMP.items():
    if eid not in es:
        sk.append(eid + '(无条目)'); continue
    f = es[eid]
    d = json.load(open(f, encoding='utf-8'))
    if d.get('comparison'):
        sk.append(eid + '(已有)'); continue
    d['comparison'] = txt
    d['pending_notes'] = (d.get('pending_notes', '') + ' 【续作DZ】补写概念辨析。')
    json.dump(d, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    n += 1
print('补写辨析:', n)
print('跳过:', sk)
