R['okuns-law'] = (
"""奥肯定律(Okun's law) 描述**失业率与产出之间的经验关系**：
**失业率每上升 1 个百分点，
产出（GDP）大约下降 2—3 个百分点**（具体系数因国家与时期而异）。
**它的含义**：
失业的变化与产出的变化**方向相反、幅度成比例**——
这为"衰退有多深"提供了一个快速的换算工具。
**为什么系数大于 1**：
产出下降时，企业往往**先减少工时与生产率**，
再裁员；同时**劳动参与率**也会下降
（灰心者退出劳动力队伍），
因此**失业率的上升幅度小于产出的下降幅度**。
**它的重要局限（必须知道）**：
①**它是经验规律，不是恒等式**——
系数在不同国家、不同时期差异很大；
②**在"无就业复苏"时期会失效**——
产出恢复了，但就业没有同步恢复
（因为生产率提高或企业先用足现有员工）；
③**它无法区分"周期性"与"结构性"失业**——
若失业是结构性的，刺激产出未必能降低它。
**与危机的关系**：
①**它是判断"衰退深度"与"需要多大刺激"的参考**；
②**危机后的"失业滞后"**（见 natural-rate-unemployment 中的疤痕效应）
会使这一关系**偏离历史模式**——
产出恢复了而失业居高不下，
这时用旧系数判断会出错；
③**它是政策沟通的常用语言**——
"需要多少增长才能让失业率降回来"。
**本库的处理**：引用其经验系数时注明**来源与适用时期**。""")

