    d = json.load(open(f, encoding='utf-8'))
    if d.get('comparison'):
        sk.append(eid + '(已有)'); continue
    d['comparison'] = txt
    d['pending_notes'] = (d.get('pending_notes', '') + ' 【续作EC】补写概念辨析。')
