R['says-law'] = (
"""萨伊定律(Say's law) 是古典经济学的核心命题：
**"供给会创造自己的需求"**——
生产本身产生的收入，恰好足以购买所生产的全部产品，
因此**总体上不存在需求不足**，
也就不会有持久的生产过剩与失业。
**它的逻辑**：
生产 → 支付工资、地租与利润 → 这些收入成为购买力
→ 用于购买其他产品 → 总供给与总需求自动相等。
**因此古典经济学的结论是**：
**衰退只是局部的、暂时的失衡**（某个部门生产过剩、另一个不足），
价格与利率的调整会迅速恢复均衡；
**政府干预没有必要，甚至有害**。
**凯恩斯的反驳（这是经济学史上最重要的分歧之一）**：
人们在不确定下**可能选择持有货币而不支出**（见 liquidity-preference），
因此收入并不必然被花掉——
**储蓄不会自动转化为投资**，
总需求可以持续低于潜在产出，
**这就是"有效需求不足"**（见 effective-demand）。
**这场争论的实际政策后果**：
大萧条期间"等待市场出清"的政策（见 laissez-faire）
造成巨大代价；
凯恩斯的框架因此成为危机应对的基础。
**但萨伊定律并未被完全抛弃**：
**"供给创造需求"在长期是成立的**——
没有生产就没有收入，
因此在讨论长期增长时，供给侧（见 supply-side）
仍然是核心。**短期与长期的分野，正是这场争论的真正落点。**""")

R['tobin-tax'] = (
"""托宾税(Tobin tax) 是托宾在 **1972 年**提出的建议：
**对即期外汇交易征收一笔很小的税**
（他建议 0.1%—0.5%），
以**抑制纯粹的短期投机**，同时不影响长期贸易与投资。
**它的设计逻辑是"**对速度征税**"**：
税的绝对额很小，但对**高频交易**的年化成本极高
（若每天进出一次，0.1% 的税一年就是数十个百分点），
从而**增加短期投机的成本而不阻碍长期资本流动**。
**支持论证**：
①**减少噪声交易与羊群效应**（见 herd-behavior），
降低汇率的过度波动；
②**为全球公共品融资**（发展援助、气候）；
③**保留各国政策空间**——减少资本流动对货币政策的冲击。
**批评与实施困难（这些是主要障碍）**：
①**需要全球协调**——单边征税只会使交易转移到其他市场；
②**"税基可迁移"**——衍生品与其他工具可替代即期交易；
③**可能损害流动性**——即使长期投资者也会承受成本；
④**收入规模不确定**；
⑤**实践中的版本很弱**——欧盟的金融交易税谈判多年未成，
部分国家（如英国）的印花税是类似但狭窄的版本。
**与危机的关系**：
该提案在每次危机后都会被重新讨论
（1997 年亚洲危机后、2008 年后），
但**从未在全球层面实施**。
**本库的处理**：记录该主张及其争议，不评价其可行性。""")

R['aggregate-supply'] = (
"""总供给(aggregate supply) 指**在给定价格水平下，
经济中所有企业愿意并且能够提供的产出总量**。
**它的形态决定了政策的效果**，因此是关键分歧点：
**短期（向上倾斜）**——价格上升时企业愿意增产，
因为**工资与成本调整滞后**（见 sticky-prices），
利润率短期改善；
**长期（垂直）**——产出由**资本、劳动与技术**决定，
与价格水平无关（这是"**货币长期中性**"，见 neutrality-of-money）；
**极端情形（垂直）**——若已充分就业，
扩张需求只会推高物价，不增加产出。
**与总需求的相互作用决定了政策后果**：
**需求扩张 + 向上倾斜的供给 → 产出增加、物价上升（温和通胀）**；
**需求扩张 + 垂直的供给 → 只有物价上升（通胀）**；
**供给收缩（如能源冲击）→ 物价上升且产出下降**
——这就是**滞胀**（见 stagflation），
也是 1970 年代让凯恩斯式需求管理失效的原因。
**与危机的关系**：
①**危机的形态取决于冲击来自哪一侧**——
需求冲击可用财政货币政策应对；
**供给冲击则没有好的需求侧对策**（扩张只会加剧通胀）；
②**潜在产出（见 potential-output）就是长期总供给的位置**，
它的估计误差直接导致政策误判；
③**危机后潜在产出可能下移**（资本与人力资本受损），
这意味着"看起来还有闲置产能"可能只是错觉。""")

R['derivative'] = (
"""金融衍生品(derivative) 指**价值来源于标的资产（股票、债券、商品、
利率、汇率或信用事件）价格变动的合约**，
包括期货、期权（见 futures、option）、
掉期（见 swap）、远期（见 forward-contract）
与信用违约互换（见 credit-default-swap）。
**四大类用途**：
①**套期保值**(hedging)——转移价格、利率或汇率风险；
②**投机**（见 speculation）——承担风险以获取收益；
③**套利**（见 arbitrage）——锁定无风险价差；
④**结构化设计**——把风险切分、重组后出售
（见 securitization、collateralized-debt-obligation）。
**它的正当功能是明确的**：
衍生品使风险可以被**单独定价与转移**，
从而提高经济效率——
农民可以锁定粮价、出口商可以锁定汇率、
银行可以转移利率风险。
**但它有三条通向危机的路径**：
①**杠杆**——衍生品只需少量保证金即可控制大额头寸
（见 margin-finance）；
②**不透明**——尤其在场外市场（见 otc），
**没人知道总敞口与对手方网络**；
③**风险的集中**——风险在转移中可能集中到少数机构
（如 AIG 的 CDS 业务），
使"分散"变成"集中"。
**一个根本的判断标准**：
**衍生品是否让风险落到更有能力承担它的人手里**——
若是，它提高效率；
**若只是让风险变得更不可见，它就是在积累脆弱性。**""")

